                    this.selectedGradeId   = '';
                    this.selectedSubjectId = '';
                    this.selectedBookId    = '';
                    this.selectedChapterId = '';
                    this.filteredGrades    = [];
                    this.filteredSubjects  = [];
                    this.filteredBooks     = [];
                    this.filteredChapters  = [];
