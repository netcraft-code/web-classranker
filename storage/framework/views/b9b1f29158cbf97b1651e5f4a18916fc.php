                                    forecolor backcolor |
                                    alignleft aligncenter alignright alignjustify |
                                    bullist numlist outdent indent |
                                    link image media table |
                                    fullscreen preview code removeformat
                                `,

                                image_advtab: true,

                                file_picker_types: 'image',
                                file_picker_callback: (cb) => {
                                    const input = document.createElement('input');
                                    input.type = 'file';
                                    input.accept = 'image/*';

                                    input.onchange = () => {
                                        const file = input.files[0];
                                        const reader = new FileReader();

                                        reader.onload = () => {
                                            cb(reader.result, { title: file.name });
                                        };

                                        reader.readAsDataURL(file);
                                    };

                                    input.click();
                                },

                                images_upload_handler: (blobInfo, progress) => new Promise((resolve, reject) => {
                                    const xhr = new XMLHttpRequest();
                                    xhr.open('POST', '/admin/tinymce/upload'); // backend route

                                    xhr.upload.onprogress = e => {
                                        progress((e.loaded / e.total) * 100);
                                    };

                                    xhr.onload = () => {
                                        if (xhr.status < 200 || xhr.status >= 300) {
                                            reject('Upload failed');
                                            return;
                                        }

                                        const json = JSON.parse(xhr.responseText);
                                        if (!json.location) {
                                            reject('Invalid response');
                                            return;
                                        }

                                        resolve(json.location);
                                    };

                                    const formData = new FormData();
                                    formData.append('_token', document.querySelector('meta[name="csrf-token"]').content);
                                    formData.append('file', blobInfo.blob(), blobInfo.filename());

                                    xhr.send(formData);
                                }),

                                directionality: 'ltr',
                            };

                            // QUESTION
                            tinymce.init({
                                selector: 'textarea.question_text',
                                height: 300,
                                ...commonConfig
                            });

                            // ANSWER
                            tinymce.init({
                                selector: 'textarea.answer_text',
                                height: 300,
                                ...commonConfig
                            });

                            // FAQ ANSWER
                            tinymce.init({
                                selector: 'textarea.faq_answer',
                                height: 200,
                                ...commonConfig
                            });

                            // TOP DESCRIPTION
                            tinymce.init({
                                selector: 'textarea.top_description',
                                height: 200,
                                ...commonConfig
                            });

                            // BOTTOM DESCRIPTION
                            tinymce.init({
                                selector: 'textarea.bottom_description',
                                height: 200,
                                ...commonConfig
                            });

                            // RELATED LINKS
                            tinymce.init({
                                selector: 'textarea.related_links',
                                height: 200,
                                ...commonConfig
                            });
                        });
                    }
                },
